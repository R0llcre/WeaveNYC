#!/usr/bin/env node
/**
 * V2-B win #1 — emit the service worker's pre-cache manifest from the
 * built Next.js static export.
 *
 * Runs as a `postbuild` hook from `apps/pwa/package.json`. Walks
 * `apps/pwa/out/_next/static/` (chunks/ + css/ + media/) plus the two
 * icon SVGs already hard-coded in the SW shell, and emits the full list
 * as a classic script at `apps/pwa/out/sw-build-manifest.js`:
 *
 *     self.__WEAVE_BUILD_ASSETS = ['/_next/static/chunks/abc.js', ...];
 *     self.__WEAVE_BUILD_VERSION = '<build-hash>';
 *
 * The SW picks this up via `importScripts('/sw-build-manifest.js')` at
 * install time. On a fresh install the SW therefore `cache.addAll(...)`s
 * the entire shell + code-split chunk graph in a single network pass —
 * return visits then hit the Cache Storage layer with zero RTTs for
 * every JS/CSS/font the app uses, turning TTI on a warm cache into
 * effectively `fetch('/') → hydrate` with no waterfall.
 *
 * The build version is a content hash over the concatenated asset
 * pathnames so any chunk-name change (which Next.js does on every
 * code change, because chunk names are content-addressed) produces a
 * new `CACHE_VERSION` for the SW and purges the old cache on activate.
 *
 * We also copy the emitted manifest into `apps/pwa/public/` so that
 * subsequent `next build` runs pick it up as a static asset even before
 * `postbuild` re-generates it — this keeps dev flows from 404-ing on
 * `/sw-build-manifest.js` in the interim.
 */
import { createHash } from 'node:crypto';
import { mkdirSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const pwaRoot = resolve(here, '..');
const outDir = resolve(pwaRoot, 'out');
const staticRoot = resolve(outDir, '_next/static');

function walk(dir) {
  const entries = [];
  const stack = [dir];
  while (stack.length) {
    const current = stack.pop();
    for (const entry of readdirSync(current)) {
      const full = join(current, entry);
      const info = statSync(full);
      if (info.isDirectory()) {
        stack.push(full);
      } else if (info.isFile()) {
        entries.push(full);
      }
    }
  }
  return entries;
}

function toPublicPath(absolutePath) {
  // Turn a filesystem path under `out/` into the URL the SW will fetch.
  // e.g. `/path/to/apps/pwa/out/_next/static/chunks/abc.js`
  //  →    `/_next/static/chunks/abc.js`
  const rel = relative(outDir, absolutePath);
  return `/${rel.split(/[\\/]/).join('/')}`;
}

function collectAssets() {
  // Static `_next` assets: chunks, css, media (fonts). These are the
  // expensive long-pole resources for first-visit TTI on slow 3G.
  let files;
  try {
    files = walk(staticRoot);
  } catch (error) {
    if (error && error.code === 'ENOENT') {
      console.warn('[gen-sw-manifest] out/_next/static missing — did `next build` run?');
      return [];
    }
    throw error;
  }

  const cacheable = files
    .filter((file) => {
      if (file.endsWith('.map')) return false;
      return /\.(js|css|woff2?|ttf|otf|svg|png|webp|avif)$/i.test(file);
    })
    .map(toPublicPath);

  // Dedup + stable order so the hash is deterministic across re-runs.
  return Array.from(new Set(cacheable)).sort();
}

function main() {
  const assets = collectAssets();
  // The SW's `CORE_ASSETS` already covers '/', '/manifest.webmanifest'
  // and the two icon SVGs via sw-predicate.js; we layer the built
  // chunk/css/font graph on top. Keeping the split means sw-predicate.js
  // stays safe to require from the vitest suite (no `out/` dependency).

  const hash = createHash('sha1').update(assets.join('\n')).digest('hex').slice(0, 12);
  const banner = `// AUTO-GENERATED by scripts/gen-sw-manifest.mjs at build time.\n// Do not hand-edit; re-runs on every \`next build\` via the \`postbuild\`\n// hook. Any edit you make here will be silently overwritten on the next\n// \`pnpm build\`.\n`;
  const body = [
    banner,
    `self.__WEAVE_BUILD_ASSETS = ${JSON.stringify(assets, null, 2)};`,
    `self.__WEAVE_BUILD_VERSION = ${JSON.stringify(hash)};`,
    '',
  ].join('\n');

  const targets = [
    resolve(outDir, 'sw-build-manifest.js'),
    // Mirror the same file into `public/` so subsequent `next build` runs
    // (and `next dev`, which serves out of `public/` rather than `out/`)
    // still resolve `/sw-build-manifest.js` to a valid script. The hash
    // will be stale in dev, but that's fine — dev doesn't exercise the
    // `install` cache path on every reload.
    resolve(pwaRoot, 'public/sw-build-manifest.js'),
  ];

  for (const target of targets) {
    mkdirSync(dirname(target), { recursive: true });
    writeFileSync(target, body, 'utf8');
  }

  console.log(
    `[gen-sw-manifest] wrote ${assets.length} assets (version ${hash}) → out/sw-build-manifest.js + public/sw-build-manifest.js`,
  );
}

main();
